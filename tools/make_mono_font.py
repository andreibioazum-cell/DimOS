#!/usr/bin/env python3
"""Turn the public-domain IBM VGA 8x8 glyph table into a C header.

The table lives in the old bare-metal tree (legacy/tools/sandbox/font8x8.py)
because that is where it was first needed. DimOS uses the same glyphs for
the boot console and every monospace label, so the header is regenerated from
that single source of truth instead of being copied by hand.

Usage: python3 tools/make_mono_font.py [output.h]
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "legacy" / "tools" / "sandbox" / "font8x8.py"
DEFAULT_OUTPUT = ROOT / "src" / "mono_font.h"


def load_glyphs() -> dict[int, bytes]:
    namespace: dict = {}
    exec(compile(SOURCE.read_text(), str(SOURCE), "exec"), namespace)
    glyphs = namespace["GLYPHS"]
    table = {}
    for code, pattern in glyphs.items():
        raw = bytes.fromhex(pattern)
        assert len(raw) == 8, hex(code)
        # font8x8 stores bit 0 as the leftmost pixel; the renderer wants the
        # classic VGA order with bit 7 leftmost.
        table[code] = bytes(sum(((byte >> bit) & 1) << (7 - bit) for bit in range(8)) for byte in raw)
    return table


def render(table: dict[int, bytes]) -> str:
    lines = [
        "/*",
        " * mono_font.h -- public domain IBM VGA 8x8 glyphs, 0x20..0x7E.",
        " *",
        " * Generated by tools/make_mono_font.py; do not edit by hand.",
        " * Each glyph is eight rows, top row first, one byte per row at",
        " * index code * 8, so a byte value can be used directly as an index.",
        " * bit 7 is the leftmost pixel.",
        " */",
        "",
        "#ifndef DIMOS_MONO_FONT_H",
        "#define DIMOS_MONO_FONT_H",
        "",
        "#define MONO_FONT_FIRST 0x20",
        "#define MONO_FONT_LAST 0x7E",
        "#define MONO_FONT_WIDTH 8",
        "#define MONO_FONT_HEIGHT 8",
        "",
        "static const unsigned char mono_font_8x8[256 * 8] = {",
    ]
    for code in range(0x00, 0x100):
        glyph = table.get(code, bytes(8))
        rows = ", ".join(f"0x{byte:02X}" for byte in glyph)
        if 0x20 <= code <= 0x7E:
            char = chr(code)
            label = "'\\'" if char == "\\" else f"'{char}'"
            lines.append(f"    {rows},   /* {code:#04x} {label} */")
        else:
            lines.append(f"    {rows},")
    lines.append("};")
    lines.append("")
    lines.append("#endif")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    output = Path(argv[1]) if len(argv) > 1 else DEFAULT_OUTPUT
    output.write_text(render(load_glyphs()))
    print(f"wrote {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
